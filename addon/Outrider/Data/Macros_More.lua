-- Data/Macros_More.lua  (Gary, 2026-11-19: "use the ideas to write our own version")
-- Outrider's own macros for the spells our first packs left out, every class.
-- Written by Outrider; the ideas come from looking at the Forever macro addons
-- and sites (MacroKit, Arcane Shortcuts, foreverwow.com), none of their text.
-- Spell names and trainer levels: the Forever client's spellbook as listed by
-- foreverchanges.pro (Data/SpellInfo.lua). Forever rule changes in the
-- explanations: as those community sources report the patch notes.
-- Conventions: help spells go to the friend under your mouse, else your
-- friendly target, else you; harmful ones to the enemy under your mouse, else
-- your target. No level field: the Macros page takes it from the spell.
-- verified = false until Gary presses them in game.

local _, ns = ...
local SRC = "Outrider (2026-11-19), Forever spellbook via foreverchanges.pro; ideas from MacroKit, Arcane Shortcuts, foreverwow.com"
local function M(cls, id, name, tags, needs, body, explain)
  return { id = id, name = name, class = cls, verified = false, tags = tags, needsSpells = needs, body = body,
    explain = explain, source = SRC }
end
