-- TameHelper macro writer (P2-08, macro part).
local T, mock = ...

local function session(opts)
  local game = mock.new(opts)
  local ns = game:loadAddon()
  game:login()
  return game, ns
end

T.describe("tame macro", function()
  T.it("updates an existing macro by name and keeps its icon", function()
    local game, ns = session({ macros = { { name = "Mystmane", icon = 132164, body = "#showtooltip Mystmane\n/cast Tame Beast", perChar = true } } })
    game:slash("tamemacro Mystmane")
    local m = game.macros[1]
    T.eq(m.icon, 132164)
    T.contains(m.body, "/targetexact Mystmane")
    T.contains(m.body, "/cast [mod,pet] Dismiss Pet; [mod][nopet,nocombat] Concussive Shot")
    T.contains(m.body, "/petattack [pet,nomod]")
    T.ok(m.body:find("/stopmacro [pet]", 1, true) < m.body:find("/cast [combat] Tame Beast", 1, true),
      "no Tame Beast while the pet is out")
    T.ok(m.body:find("/stopmacro [channeling]", 1, true) == m.body:find("\n", 1, true) + 1, "never breaks the channel")
    T.ok(#m.body <= 255)
    T.eq(ns.MacroEngine.Errors(m.body), 0)
    T.eq(#game.macros, 1)
    T.contains(game:chatText(), "updated macro 'Mystmane'")
  end)

  T.it("solo: no pet; pull, tame, and Wing Clip then tame again if it breaks", function()
    local game, ns = session({ macros = { { name = "Mystmane", icon = 132164, body = "old", perChar = true } } })
    game:slash("tamemacro solo mystmane")
    local m = game.macros[1]
    T.contains(m.body, "/targetexact Mystmane")
    T.contains(m.body, "/cast [nocombat][mod:shift] Concussive Shot")
    T.contains(m.body, "/castsequence [combat] reset=combat/shift Tame Beast, Wing Clip")
    T.eq(m.body:find("Dismiss Pet", 1, true), nil)
    T.eq(m.body:find("petattack", 1, true), nil)
    T.ok(m.body:find("/stopmacro [channeling]", 1, true) == m.body:find("\n", 1, true) + 1, "never breaks the channel")
    T.ok(#m.body <= 255)
    T.eq(ns.MacroEngine.Errors(m.body), 0)
    T.contains(game:chatText(), "updated macro 'Mystmane'")
  end)

  T.it("trap: Freezing Trap, pull onto it, tame, Wing Clip and tame again", function()
    local game, ns = session({ macros = { { name = "Mystmane", icon = 132164, body = "old", perChar = true } } })
    game:slash("tamemacro trap mystmane")
    T.eq(#game.macros, 2, "its own macro; the usual one stays")
    T.eq(game.macros[1].body, "old")
    local m = game.macros[2]
    T.eq(m.name, "Mystmane Trap")
    T.contains(m.body, "/targetexact Mystmane")
    T.contains(m.body, "/castsequence [nocombat] reset=combat Freezing Trap, Concussive Shot")
    T.contains(m.body, "/cast [combat,mod] Freezing Trap")
    T.contains(m.body, "/castsequence [combat] reset=combat/shift Tame Beast, Wing Clip")
    T.eq(m.body:find("Dismiss Pet", 1, true), nil)
    T.eq(m.body:find("/stopmacro [channeling]", 1, true), 1, "never breaks the channel")
    T.ok(#m.body <= 255, "fits: " .. #m.body)
    T.eq(ns.MacroEngine.Errors(m.body), 0)
  end)

  T.it("creates a per-character macro when none exists", function()
    local game = session()
    game:slash("tamemacro Ghost Howl")
    T.eq(game.macros[1].name, "Ghost Howl")
    T.ok(game.macros[1].perChar)
    T.contains(game.macros[1].body, "/targetexact Ghost Howl")
  end)

  T.it("refuses in combat and for other classes, without errors", function()
    local game, ns = session()
    game.combat = true
    game:slash("tamemacro Mystmane")
    T.eq(#game.macros, 0)
    T.contains(game:chatText(), "not in combat")
    local g2 = mock.new({ class = "PRIEST" })
    local ns2 = g2:loadAddon()
    g2:login()
    g2:slash("tamemacro Mystmane")
    T.eq(#g2.macros, 0)
    T.eq(#ns.Errors.list + #ns2.Errors.list, 0)
  end)
end)

T.describe("tame macro names", function()
  T.it("lowercase input keeps the macro's name and capitalizes the target", function()
    local game = mock.new({ macros = { { name = "Mystmane", icon = 1, body = "x", perChar = true } } })
    game:loadAddon()
    game:login()
    game:slash("tamemacro mystmane")
    T.eq(game.macros[1].name, "Mystmane")
    T.contains(game.macros[1].body, "/targetexact Mystmane")
    T.contains(game.macros[1].body, "Tame Beast")
    game:slash("tamemacro ghost howl")
    T.eq(game.macros[2].name, "Ghost Howl")
  end)
end)

T.describe("tame macro case repair", function()
  T.it("a lowercased beast macro gets its capitals back; custom names are kept", function()
    local game = mock.new({ macros = { { name = "mystmane", icon = 1, body = "x", perChar = true },
                                        { name = "My Tamer", icon = 2, body = "y", perChar = true } } })
    game:loadAddon()
    game:login()
    game:slash("tamemacro Mystmane")
    T.eq(game.macros[1].name, "Mystmane")
  end)

  T.it("a misspelled tame macro is fixed at login, and a typo in the command is corrected", function()
    local game = mock.new({ macros = { { name = "Mystmade", icon = "x", perChar = true,
      body = "#showtooltip\n/stopmacro [channeling]\n/cleartarget\n/targetexact Mystmade\n/cast Tame Beast" } } })
    local ns = game:loadAddon()
    game:login()
    ns.db.global.discovered = { npcs = { [259388] = { name = "Mystmane", mapID = 2521 } }, recent = {} }
    ns.Modules:Get("TameHelper"):FixTypos()
    T.eq(game.macros[1].name, "Mystmane")
    T.contains(game.macros[1].body, "/targetexact Mystmane")
    game:slash("tamemacro Mystmnae")
    T.contains(game:chatText(), "using Mystmane")
    T.eq(#ns.Errors.list, 0)
  end)
end)
