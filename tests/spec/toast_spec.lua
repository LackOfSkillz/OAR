-- Toasts (P1-06).
local T, mock = ...

local function session(opts)
  local game = mock.new(opts)
  local ns = game:loadAddon()
  game:login()
  ns.Modules:SetEnabled("AutoCheck", false) -- its timers/combat hooks would skew these counts
  return game, ns
end

T.describe("toast", function()
  T.it("shows, plays its sound and expires after its duration", function()
    local game, ns = session()
    ns.Toast:Show({ title = "A", text = "b", sound = 8959, duration = 2 })
    T.eq(ns.Toast:Count(), 1)
    T.same(game.sounds, { 8959 })
    game:advance(1)
    T.eq(ns.Toast:Count(), 1)
    game:advance(2)
    T.eq(ns.Toast:Count(), 0)
    T.eq(ns.Timer.Pending(), 0)
  end)

  T.it("stacks at most 3; a 4th pushes out the oldest", function()
    local _, ns = session()
    for i = 1, 4 do ns.Toast:Show({ title = "t" .. i }) end
    T.eq(ns.Toast:Count(), 3)
    T.eq(ns.Toast.visible[1].title:GetText(), "t2")
    T.eq(ns.Toast.visible[3].title:GetText(), "t4")
  end)

  T.it("hovering delays the fade", function()
    local game, ns = session()
    local f = ns.Toast:Show({ title = "x", duration = 1 })
    f.__mouseOver = true
    game:advance(5)
    T.eq(ns.Toast:Count(), 1)
    f.__mouseOver = false
    game:advance(3)
    T.eq(ns.Toast:Count(), 0)
  end)

  T.it("dragging a toast saves the anchor per character, and it survives a reload", function()
    local game, ns = session()
    local f = ns.Toast:Show({ title = "x" })
    local a = ns.Toast:Anchor()
    a:ClearAllPoints()
    a:SetPoint("TOP", game.env.UIParent, "TOP", 40, -200)
    f.__scripts.OnDragStop(f)
    local sv = game:logout()
    local game2 = mock.new({ savedVariables = sv })
    local ns2 = game2:loadAddon()
    game2:login()
    local p, _, _, x, y = ns2.Toast:Anchor():GetPoint(1)
    T.eq(p, "TOP")
    T.eq(x, 40)
    T.eq(y, -200)
  end)

  T.it("a toast button is a secure button with the macro, released on expiry", function()
    local game, ns = session()
    local _, free = ns.SecureButtons:Counts()
    local f = ns.Toast:Show({ title = "Rare", button = { label = "Target", macro = "/target The Rake" }, duration = 1 })
    T.eq(f.secure:GetAttribute("macrotext"), "/target The Rake")
    T.eq(f.secure.text:GetText(), "Target")
    game:advance(3)
    T.eq(f.secure, nil)
    local _, after = ns.SecureButtons:Counts()
    T.eq(after, free)
  end)

  T.it("in combat a toast still shows, with no protected calls, and the button works after combat", function()
    local game, ns = session()
    ns.Modules:Get("PetStatus"):Settings().warnAspect = false -- isolate generic toast behavior
    game:setCombat(true)
    local f = ns.Toast:Show({ title = "Rare", text = "seen", button = { label = "Target", macro = "/target X" }, duration = 30 })
    T.eq(ns.Toast:Count(), 1)
    T.eq(#game.blocked, 0)
    T.contains(f.text:GetText(), "after combat")
    game:setCombat(false)
    T.eq(f.secure:GetAttribute("macrotext"), "/target X")
    T.ok(f.secure:IsShown())
  end)

  T.it("/ride selftest toast shows the sample with sound", function()
    local game, ns = session()
    game:slash("selftest toast")
    T.eq(ns.Toast:Count(), 1)
    T.eq(#game.sounds, 1)
    T.eq(#ns.Errors.list, 0)
  end)
end)

T.describe("toast in combat with buttons", function()
  T.it("does not move toasts that carry secure buttons during combat", function()
    local game, ns = session()
    ns.Toast:Show({ title = "a", button = { label = "T", macro = "/wave" }, duration = 1 })
    ns.Toast:Show({ title = "b", button = { label = "T", macro = "/wave" }, duration = 60 })
    game:setCombat(true)
    local second = ns.Toast.visible[2]
    local before = select(5, second:GetPoint(1))
    game:advance(3) -- first toast expires and is dismissed in combat
    T.eq(select(5, second:GetPoint(1)), before, "not moved in combat")
    game:setCombat(false)
    T.eq(select(5, second:GetPoint(1)), 0, "moved up after combat")
    T.eq(#game.blocked, 0)
  end)
end)

T.describe("toast buttons are never anchored to toasts", function()
  T.it("places the secure button against UIParent, and dragging moves no protected frame", function()
    local game, ns = session()
    local f = ns.Toast:Show({ title = "Rare", button = { label = "Target", macro = "/wave" } })
    local _, rel = f.secure:GetPoint(1)
    T.eq(rel, game.env.UIParent)
    f.__scripts.OnDragStart(f)
    f.__scripts.OnDragStop(f)
    T.eq(game.secureAnchoredToInsecure, nil)
    T.ok(f.secure:IsShown())
    T.eq(#game.blocked, 0)
  end)
end)
