-- OI01-11: degraded capability is reported, not faked; disabling cleans up.
local T, mock = ...

T.describe("event and timer semantics", function()
  T.it("an event the client refuses returns unavailable once and is never retried", function()
    local game = mock.new()
    game.blockedEvents.SOME_FUTURE_EVENT = true
    local ns = game:loadAddon()
    game:login()
    local before = game.forbiddenAttempts or 0
    local h, why = ns.Events:On("SOME_FUTURE_EVENT", { name = "probe" }, function() end)
    T.eq(h, nil)
    T.eq(why, "unavailable")
    T.eq(ns.Events:Count("SOME_FUTURE_EVENT"), 0, "no handler kept for an event that can't fire")
    local h2, why2 = ns.Events:On("SOME_FUTURE_EVENT", { name = "probe2" }, function() end)
    T.eq(h2, nil)
    T.eq(why2, "unavailable")
    T.eq((game.forbiddenAttempts or 0) - before, 1, "registration tried once, not on every call")
    -- a module's On passes the answer through
    local m = ns.Modules:Get("Welcome")
    local mh, mwhy = m:On("SOME_FUTURE_EVENT", function() end)
    T.eq(mh, nil)
    T.eq(mwhy, "unavailable")
    T.eq(#ns.Errors.list, 0)
  end)

  T.it("a registrable event still returns a handle", function()
    local game = mock.new()
    local ns = game:loadAddon()
    game:login()
    local h = ns.Events:On("BAG_UPDATE_DELAYED", { name = "probe" }, function() end)
    T.ok(h and h.fn)
  end)

  T.it("disabling a module cancels its events and the timers it owns", function()
    local game = mock.new()
    local ns = game:loadAddon()
    game:login()
    local m = ns.Modules:Get("Welcome")
    local fired = 0
    m:On("BAG_UPDATE_DELAYED", function() fired = fired + 1 end)
    m:After(5, function() fired = fired + 100 end)
    local ticks = 0
    m:Ticker(1, function() ticks = ticks + 1 end)
    game:advance(1.5)
    T.eq(ticks, 1)
    local pendingBefore = ns.Timer.Pending()
    ns.Modules:Disable(m)
    T.eq(ns.Timer.Pending(), pendingBefore - 2, "both owned timers cancelled")
    game:fire("BAG_UPDATE_DELAYED")
    game:advance(10)
    T.eq(fired, 0, "no event and no timer after disable")
    T.eq(ticks, 1)
  end)

  T.it("an owned After that has fired is forgotten (no leak)", function()
    local game = mock.new()
    local ns = game:loadAddon()
    game:login()
    local m = ns.Modules:Get("Welcome")
    m:After(1, function() end)
    game:advance(2)
    T.eq(next(m.timers), nil)
  end)

  T.it("LagCheck stops its sampler when the module is switched off mid-check", function()
    local game = mock.new()
    local ns = game:loadAddon()
    game:login()
    local L = ns.Modules:Get("LagCheck")
    T.ok(L and L.enabled, "LagCheck is on by default")
    L:Start(60)
    T.ok(L.on)
    ns.Modules:Disable(L)
    T.no(L.on)
    T.eq(L.sampler, nil)
  end)
end)
