local T, mock = ...
local function play()
  local game = mock.new({ level = 20 })
  game.xp, game.xpMax = 800, 1000
  local ns = game:loadAddon()
  game:login()
  return game, ns
end
T.describe("XP60 opted-in recorder", function()
  T.it("is off by default and records nothing until explicitly enabled", function()
    local g, ns = play()
    T.no(ns.SessionXP.enabled)
    g.xp = 950
    g:fire("PLAYER_XP_UPDATE", "player")
    T.eq(#ns.SessionXP:Store().history, 0)
  end)
  T.it("writes a logout snapshot and labels candidate observation time", function()
    local game, ns = play()
    ns.Modules:SetEnabled("SessionXP", true)
    T.ok(type(ns.WhatNow.lastSnap) == "table")
    T.ok(type(ns.WhatNow.lastSnap.seenAt) == "number")
    game:logout()
    local saved = game.env.Outrider_Snapshots[ns.db.key]
    T.ok(saved and saved.takenAt)
    T.ok(type(saved.modules) == "table")
    T.ok(type(saved.modules.WhatNow) == "table")
    T.ok(saved.modules.WhatNow.seenAt)
    T.eq(#ns.Errors.list,0)
  end)
  T.it("records XP across a level-up, zone time, quest hand-in and final logout", function()
    local g, ns = play()
    g:slash("xp60 on")
    T.ok(ns.SessionXP.enabled)
    g:advance(120)
    g.xp = 950
    g:fire("PLAYER_XP_UPDATE", "player")
    g:advance(180)
    g.player.level, g.xp, g.xpMax = 21, 100, 1100
    g:fire("PLAYER_LEVEL_UP", 21)
    g:fire("QUEST_TURNED_IN", 1234)
    local save = g:logout()
    local h = ns.db.char.xp60.history
    T.eq(#h, 1)
    T.eq(h[1].xpEarned, 300)
    T.eq(h[1].durationSeconds, 300)
    T.eq(h[1].levelStart, 20)
    T.eq(h[1].levelEnd, 21)
    T.eq(h[1].questsTurnedIn[1].questID, 1234)
    T.ok(h[1].final)
    T.contains(save, "xp60")
    T.eq(#ns.Errors.list, 0)
  end)
  T.it("does not fabricate XP for resets or level jumps", function()
    local g, ns = play()
    g:slash("xp60 on")
    g.player.level, g.xp = 23, 120
    g:fire("PLAYER_XP_UPDATE", "player")
    T.no(ns.SessionXP.current.xpVerified)
    T.ok(ns.SessionXP.current.flags.rolloverUnknown)
    g:logout()
    T.eq(ns.db.char.xp60.history[1].xpEarned, 0)
  end)
  T.it("keeps only 20 bounded records and marks interruption as partial", function()
    local g, ns = play()
    g:slash("xp60 on")
    for i=1,26 do
      ns.SessionXP:Checkpoint(false)
      ns.SessionXP:Start()
    end
    T.eq(#ns.db.char.xp60.history, 20)
    T.no(ns.db.char.xp60.history[20].final)
    T.ok(ns.db.char.xp60.history[20].flags.incomplete)
    g:slash("xp60 clear")
    T.eq(#ns.db.char.xp60.history, 0)
    T.eq(#ns.Errors.list, 0)
  end)
end)
