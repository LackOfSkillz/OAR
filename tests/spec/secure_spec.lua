-- Secure button pool (P1-05).
local T, mock = ...

local function session(opts)
  local game = mock.new(opts)
  local ns = game:loadAddon()
  game:login()
  ns.Modules:SetEnabled("AutoCheck", false) -- its timers/combat hooks would skew these counts
  return game, ns
end

T.describe("secure buttons", function()
  T.it("pre-creates buttons at login, out of combat", function()
    local game, ns = session()
    local all, free = ns.SecureButtons:Counts()
    T.eq(all, 4)
    T.eq(free, 4)
    T.eq(#game.blocked, 0)
    local b = ns.SecureButtons.all[1]
    T.eq(b.__template, "SecureActionButtonTemplate")
    T.same(b.__clicks, { "AnyUp" })
  end)

  T.it("acquiring in combat returns a pre-created button without protected calls", function()
    local game, ns = session()
    game:setCombat(true)
    local b = ns.SecureButtons:Acquire("test")
    T.ok(b)
    T.eq(#game.blocked, 0)
    game:setCombat(false)
  end)

  T.it("SetMacro out of combat applies at once and the click runs the macro", function()
    local game, ns = session()
    local b = ns.SecureButtons:Acquire("test")
    T.ok(ns.SecureButtons:SetMacro(b, "/wave"))
    T.eq(b:GetAttribute("type"), "macro")
    T.eq(b:GetAttribute("macrotext"), "/wave")
    b:Click()
    T.same(game.macrosRun, { "/wave" })
  end)

  T.it("SetMacro in combat is queued, only the latest applies, after combat", function()
    local game, ns = session()
    local b = ns.SecureButtons:Acquire("test")
    ns.SecureButtons:SetMacro(b, "/wave")
    game:setCombat(true)
    T.no(ns.SecureButtons:SetMacro(b, "/cheer"))
    ns.SecureButtons:SetMacro(b, "/dance")
    T.eq(b:GetAttribute("macrotext"), "/wave", "unchanged during combat")
    T.eq(#game.blocked, 0, "no protected calls in combat")
    game:setCombat(false)
    T.eq(b:GetAttribute("macrotext"), "/dance")
  end)

  T.it("release resets attributes and returns the button to the pool", function()
    local game, ns = session()
    local _, before = ns.SecureButtons:Counts()
    local b = ns.SecureButtons:Acquire("test")
    ns.SecureButtons:SetMacro(b, "/wave")
    ns.SecureButtons:SetShown(b, true)
    ns.SecureButtons:Release(b)
    T.eq(b:GetAttribute("type"), nil)
    T.eq(b:GetAttribute("macrotext"), nil)
    T.no(b:IsShown())
    local _, after = ns.SecureButtons:Counts()
    T.eq(after, before)
  end)

  T.it("release in combat cancels a queued macro and defers the reset", function()
    local game, ns = session()
    local b = ns.SecureButtons:Acquire("test")
    ns.SecureButtons:SetMacro(b, "/wave")
    game:setCombat(true)
    ns.SecureButtons:SetMacro(b, "/cheer")
    ns.SecureButtons:Release(b)
    T.eq(#game.blocked, 0)
    game:setCombat(false)
    T.eq(b:GetAttribute("macrotext"), nil)
  end)

  T.it("the pool refills out of combat when it runs dry", function()
    local _, ns = session()
    for _ = 1, 4 do T.ok(ns.SecureButtons:Acquire("x")) end
    local _, free = ns.SecureButtons:Counts()
    T.ok(free >= 1)
  end)

  T.it("/ride selftest button swaps /wave and /cheer, queued in combat", function()
    local game, ns = session()
    game:slash("selftest button")
    local b = ns.SecureButtons.test
    T.eq(b:GetAttribute("macrotext"), "/wave")
    T.ok(b:IsShown())
    game:setCombat(true)
    game:slash("selftest button")
    T.eq(b:GetAttribute("macrotext"), "/wave")
    T.eq(#game.blocked, 0)
    game:setCombat(false)
    T.eq(b:GetAttribute("macrotext"), "/cheer")
    b:Click()
    T.same(game.macrosRun, { "/cheer" })
    T.eq(#ns.Errors.list, 0)
  end)
end)

T.describe("secure buttons and key-down setting", function()
  T.it("registers only AnyDown when ActionButtonUseKeyDown is 1", function()
    local game = mock.new({ cvars = { ActionButtonUseKeyDown = "1" } })
    local ns = game:loadAddon()
    game:login()
    T.same(ns.SecureButtons.all[1].__clicks, { "AnyDown" })
  end)
end)
