-- Chat highlights, spam filter, URLs (P7-08).
local T, mock = ...

T.describe("chat", function()
  T.it("highlights Gary's name and own words, feeds once, hides repeats, links URLs", function()
    local game = mock.new()
    local ns = game:loadAddon()
    game:login()
    local hidden, text = game:chatLine("CHAT_MSG_CHANNEL", "anyone seen torrant today?", "Bob")
    T.no(hidden)
    T.contains(text, "|cffffc84dtorrant|r")
    T.eq(ns.Feed.list[1].title, "Chat: your name")
    hidden = game:chatLine("CHAT_MSG_CHANNEL", "anyone seen torrant today?", "Bob")
    T.ok(hidden, "same line, same sender within 60 s")
    T.no((game:chatLine("CHAT_MSG_GUILD", "anyone seen torrant today?", "Bob")), "guild is never muted")
    game:slash("chat word add linen")
    local _, t2 = game:chatLine("CHAT_MSG_CHANNEL", "WTS Linen Cloth cheap", "Ann")
    T.contains(t2, "|cffffc84dLinen|r")
    local _, t3 = game:chatLine("CHAT_MSG_SAY", "guide at https://example.com/a?b=1 ok", "Cid")
    T.contains(t3, "|Haddon:Outrider:url:https://example.com/a?b=1|h")
    local _, t4 = game:chatLine("CHAT_MSG_SAY", "nothing here", "Cid")
    T.eq(t4, "nothing here")
    T.eq(ns.Chat.Plain("|cffffc84dhi|r |Hitem:1|h[Bow]|h"), "hi [Bow]")
    T.eq(#ns.Errors.list, 0)
  end)
end)

T.describe("persistent chat history", function()
  T.it("retains 600 bounded lines across reload and separates people by whisper", function()
    local game = mock.new()
    local ns = game:loadAddon()
    game:login()
    for i = 1, 620 do ns.Chat:RememberLine("CHAT_MSG_GUILD", "line " .. i, "Guild") end
    T.eq(#ns.Chat.archive, 600)
    T.eq(ns.Chat.archive[1].text, "line 21")
    ns.Chat:RememberLine("CHAT_MSG_WHISPER", "hello", "Bob")
    ns.Chat:RememberLine("CHAT_MSG_WHISPER_INFORM", "reply", "Bob")
    T.eq(#ns.Chat:History("bob"), 2)
    T.eq(ns.Chat:History("Bob")[1].text, "reply")
    game:slash("history Bob 5")
    T.eq(#ns.Errors.list, 0)
  end)

  T.it("does not persist secrets or disabled archives and filters only once per line", function()
    local game = mock.new()
    local ns = game:loadAddon()
    game:login()
    local size = #ns.Chat.archive
    game:chatLine("CHAT_MSG_GUILD", "Hello", "Bob", {}, "", 2100)
    T.eq(#ns.Chat.archive, size + 1)
    ns.Chat:Settings().chatArchive = false
    ns.Chat:RememberLine("CHAT_MSG_GUILD", "off", "Bob")
    T.eq(#ns.Chat.archive, size + 1)
    ns.Chat:RememberLine("CHAT_MSG_WHISPER", { __secret = true }, "Bob")
    T.eq(#ns.Chat:History("Bob"), 0)
  end)
end)

T.describe("class-aware chat author rendering", function()
  T.it("only colors known class GUIDs and leaves unknown names unchanged", function()
    local game = mock.new()
    local ns = game:loadAddon()
    game:login()
    game.base.GetPlayerInfoByGUID = function(id)
      if id == "Player-100" then return "Hunter", "HUNTER" end
    end
    game.env.GetPlayerInfoByGUID = game.base.GetPlayerInfoByGUID
    local colored = ns.Chat:ColorAuthor("Elora", "Player-100")
    T.contains(colored, "Elora|r")
    T.contains(colored, "|cff")
    T.eq(ns.Chat:ColorAuthor("Elora", "NPC-100"), nil)
    T.eq(ns.Chat:ColorAuthor("Elora", nil), nil)
  end)
end)

T.describe("chat triage", function()
  T.it("opens the LFG tab once and routes Trade and LFG lines there, not the main window", function()
    local game = mock.new()
    local ns = game:loadAddon()
    game:login()
    local lfg = ns.Chat.lfgFrame
    T.ok(lfg, "tab created")
    T.eq(game.chatWindows[3], "LFG")
    local main = game.env.ChatFrame1 or {}
    T.ok((game:chatLine("CHAT_MSG_CHANNEL", "WTS linen bolts", "Ann", main, "Trade - English", 1)), "hidden in main")
    T.no((game:chatLine("CHAT_MSG_CHANNEL", "WTS linen bolts", "Ann", lfg, "Trade - English", 1)), "shown in LFG tab, same line not muted as spam")
    T.ok((game:chatLine("CHAT_MSG_CHANNEL", "LFM deadmines need heals", "Bob", main, "General - Mulgore", 2)))
    T.no((game:chatLine("CHAT_MSG_CHANNEL", "anyone know where the bank is", "Cid", main, "General - Mulgore", 3)))
    T.ok((game:chatLine("CHAT_MSG_CHANNEL", "anyone know where the bank is", "Cid", lfg, "General - Mulgore", 3)), "non-LFG general not in LFG tab")
    game:fire("CHAT_MSG_CHANNEL", "x", "Ann", nil, nil, nil, nil, nil, nil, "Trade - English")
    T.eq(game.addedChannels["Trade - English"], lfg)
    game:login()
    T.eq(#game.chatWindows, 3, "never a second tab")
  end)

  T.it("marks lines that want your role, and the switch turns routing off", function()
    local game = mock.new()
    local ns = game:loadAddon()
    game:login()
    local _, text = game:chatLine("CHAT_MSG_CHANNEL", "LF2M RFC need dps", "Bob", ns.Chat.lfgFrame, "LookingForGroup", 10)
    T.contains(text, "[for you]")
    T.eq(ns.Feed.list[1].title, "Group wants you")
    local _, t2 = game:chatLine("CHAT_MSG_CHANNEL", "LF healer for WC", "Dee", ns.Chat.lfgFrame, "LookingForGroup", 11)
    T.no(t2:find("for you", 1, true), "hunters are not healers")
    game:slash("chat lfgtab off")
    T.no((game:chatLine("CHAT_MSG_CHANNEL", "WTS ore", "Ann", {}, "Trade - English", 12)), "routing off: stays in main")
    T.eq(#ns.Errors.list, 0)
  end)
end)
