-- Waypoints (P3-01) and coordinates (P3-10).
local T, mock = ...

local function session(opts)
  local game = mock.new(opts)
  local ns = game:loadAddon()
  game:login()
  ns.Modules:SetEnabled("AutoCheck", false)
  return game, ns
end

T.describe("waypoints", function()
  T.it("/ride way sets a Blizzard user waypoint on the current map and supertracks it", function()
    local game, ns = session()
    game:slash("way 50 60 test spot")
    T.eq(game.userWaypoint.uiMapID, 1412)
    T.eq(game.userWaypoint.x, 0.5)
    T.eq(game.userWaypoint.y, 0.6)
    T.ok(game.superTracked)
    T.eq(ns.Waypoints.current.backend, "blizzard")
    T.contains(game:chatText(), "waypoint test spot at 50.0, 60.0 (blizzard)")
  end)

  T.it("clears itself on arrival, and the arrival check stops", function()
    local game, ns = session()
    game:slash("way 60 37")
    game:advance(1.5)
    T.ok(ns.Waypoints.current, "100 yards away: still set")
    game.opts.x = 0.599
    game:advance(1.5)
    T.eq(ns.Waypoints.current, nil)
    T.eq(game.userWaypoint, nil)
    T.eq(ns.Timer.Pending(), 0)
  end)

  T.it("rejects bad input and clears with /ride way clear", function()
    local game, ns = session()
    T.no(ns.Waypoints:Set(1412, 2, 0.5))
    game:slash("way 10 10")
    game:slash("way clear")
    T.eq(ns.Waypoints.current, nil)
  end)

  T.it("/ride coords prints the map and two-decimal coordinates", function()
    local game = session()
    game:slash("coords")
    T.contains(game:chatText(), "Mulgore (map 1412): 46.00, 37.00")
  end)

  T.it("coords and minimap pins tick only while moving", function()
    local game, ns = session()
    T.eq(ns.Timer.Pending(), 0)
    game:fire("PLAYER_STARTED_MOVING")
    T.ok(ns.Modules:Get("Coords").ticker)
    T.ok(ns.Modules:Get("MinimapPins").ticker)
    game:fire("PLAYER_STOPPED_MOVING")
    T.eq(ns.Timer.Pending(), 0)
  end)
end)

T.describe("world map cursor coordinates", function()
  T.it("shows cursor position relative to the open map canvas, not player coords", function()
    local game, ns = session()
    game.mapShownID = 1412
    game.env.WorldMapFrame:Show()
    game.cursorX, game.cursorY = 600, 350
    local M = ns.Modules:Get("Coords")
    local mapID, x, y = M:CursorPosition()
    T.eq(mapID, 1412)
    T.eq(x, 0.5)
    T.eq(y, 0.5)
    M:UpdateCursor()
    T.contains(M.cursorText:GetText(), "50.00, 50.00")
    game.cursorX = 3000
    M:UpdateCursor()
    T.contains(M.cursorText:GetText(), "Cursor: --")
  end)
end)

T.describe("waypoint queue", function()
  T.it("enqueues two stops, advances on arrival and persists the remainder", function()
    local game, ns = session()
    game:slash("way add 60 37 First")
    game:slash("way add 70 37 Second")
    T.eq(#ns.Waypoints:Settings().queue, 2)
    T.eq(ns.Waypoints.current, nil)
    game:slash("way start")
    T.eq(ns.Waypoints.current.title, "First")
    game.opts.x = 0.6
    game:advance(1.5)
    T.eq(ns.Waypoints.current.title, "Second")
    T.eq(#ns.Waypoints:Settings().queue, 1)
    game.opts.x = 0.7
    game:advance(1.5)
    T.eq(ns.Waypoints.current, nil)
    T.eq(#ns.Waypoints:Settings().queue, 0)
    T.eq(ns.Waypoints:Settings().queueRunning, false)
    T.eq(#ns.Errors.list, 0)
  end)

  T.it("manual waypoints pause the route and avoid overwriting the user", function()
    local game, ns = session()
    game:slash("way add 60 37 First")
    game:slash("way add 70 37 Second")
    game:slash("way start")
    game:slash("way 80 80 Manual")
    T.eq(ns.Waypoints.current.title, "Manual")
    T.eq(ns.Waypoints:Settings().queueRunning, false)
    T.eq(#ns.Waypoints:Settings().queue, 2)
    game:slash("way start")
    T.eq(ns.Waypoints.current.title, "Manual")
    game:slash("way clear")
    game:slash("way resume")
    T.eq(ns.Waypoints.current.title, "First")
    game:slash("way clearqueue")
    T.eq(ns.Waypoints.current, nil)
  end)

  T.it("supports explicit map IDs and validates queuing inputs", function()
    local game, ns = session()
    game:slash("way add 1412 40 50 My stop")
    T.eq(ns.Waypoints:Settings().queue[1].mapID, 1412)
    local n = #ns.Waypoints:Settings().queue
    game:slash("way add UnknownZone 40 50")
    T.eq(#ns.Waypoints:Settings().queue, n)
    T.eq(ns.Waypoints:QueueAdd(1412, -1, 0.5), false)
  end)
end)

T.describe("corpse navigation", function()
  T.it("does not point to a guessed healer while corpse position is unknown", function()
    local game, ns = session()
    ns.Waypoints:Set(1412, 0.6, 0.7, "Before death")
    local original = ns.Waypoints.current
    game:fire("PLAYER_DEAD")
    T.eq(ns.Waypoints.current, original)
    game.isGhost = true
    game:fire("PLAYER_ALIVE")
    T.eq(ns.Waypoints.current, original)
    T.ok(ns.Modules:Get("Nearest").corpseTicker)
    game:fire("PLAYER_UNGHOST")
    T.eq(ns.Timer.Pending(), 1, "only the existing waypoint arrival timer remains")
  end)

  T.it("points at the actual corpse after release and restores prior waypoint on resurrection", function()
    local game, ns = session()
    ns.Waypoints:Set(1412, 0.6, 0.7, "Before death")
    game:fire("PLAYER_DEAD")
    game.isGhost = true
    game.corpse = { mapID = 1412, x = 0.42, y = 0.31 }
    game:fire("PLAYER_ALIVE")
    T.eq(ns.Waypoints.current.title, "Your corpse")
    T.eq(ns.Waypoints.current.x, 0.42)
    T.eq(ns.Waypoints.current.y, 0.31)
    game.isGhost = false
    game:fire("PLAYER_UNGHOST")
    T.eq(ns.Waypoints.current.title, "Before death")
    T.eq(ns.Waypoints.current.x, 0.6)
    T.eq(#ns.Errors.list, 0)
  end)

  T.it("does not restore a previous waypoint over one the player set while dead", function()
    local game, ns = session()
    ns.Waypoints:Set(1412, 0.6, 0.7, "Before death")
    game.corpse = { mapID = 1412, x = 0.4, y = 0.3 }
    game:fire("PLAYER_DEAD")
    T.eq(ns.Waypoints.current.title, "Your corpse")
    ns.Waypoints:Set(1412, 0.5, 0.5, "My new waypoint")
    game:fire("PLAYER_UNGHOST")
    T.eq(ns.Waypoints.current.title, "My new waypoint")
  end)

  T.it("restores the previous waypoint if the ghost arrived at the corpse before resurrecting", function()
    local game, ns = session()
    ns.Waypoints:Set(1412, 0.6, 0.7, "Original journey")
    game.corpse = { mapID = 1412, x = 0.5, y = 0.6 }
    game:fire("PLAYER_DEAD")
    T.eq(ns.Waypoints.current.title, "Your corpse")
    game.opts.x, game.opts.y = 0.5, 0.6
    game:advance(1.5)
    T.eq(ns.Waypoints.current, nil, "corpse arrow clears when ghost reaches it")
    game:fire("PLAYER_UNGHOST")
    T.eq(ns.Waypoints.current.title, "Original journey")
    T.eq(#ns.Errors.list, 0)
  end)

  T.it("uses no timer when corpse coordinates are immediately available", function()
    local game, ns = session()
    game.corpse = { mapID = 1412, x = 0.5, y = 0.6 }
    game:fire("PLAYER_DEAD")
    T.eq(ns.Waypoints.current.title, "Your corpse")
    T.eq(ns.Modules:Get("Nearest").corpseTicker, nil)
    T.eq(#ns.Errors.list, 0)
  end)
end)

T.describe("world axes calibration", function()
  T.it("detects whether map->world returns its axes in the other order", function()
    local game, ns = session()
    T.eq(ns.Waypoints.swap, false, "mock returns the same order as UnitPosition")
    -- now make the map API hand back swapped axes
    local orig = game.env.C_Map.GetWorldPosFromMapPos
    game.env.C_Map.GetWorldPosFromMapPos = function(m, v) return 1, { GetXY = function() return v.y * 1000, v.x * 1000 end } end
    ns.Waypoints:Calibrate()
    T.eq(ns.Waypoints.swap, true)
    local _, x, y = ns.Waypoints.WorldPos(1412, 0.46, 0.37)
    T.eq(x, 460)
    T.eq(y, 370)
    game.env.C_Map.GetWorldPosFromMapPos = orig
  end)
end)

T.describe("requested pins", function()
  T.it("sets a requested pin once, only on the named character", function()
    local game = mock.new({ name = "Khreos" })
    local ns = game:loadAddon()
    game:login()
    local w = ns.Waypoints.current
    T.ok(w and w.title:find("Slydris", 1, true), "Slydris pin set on Khreos")
    T.eq(w.mapID, 2521)
    ns.Waypoints:Clear("test", true)
    ns.Waypoints:Requests()
    T.eq(ns.Waypoints.current, nil)
    local g2 = mock.new({ name = "Torrant" })
    local ns2 = g2:loadAddon()
    g2:login()
    T.eq(ns2.Waypoints.current, nil)
  end)
end)
