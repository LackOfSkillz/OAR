-- First-run setup and accessibility (P7-12).
local T, mock = ...

T.describe("setup", function()
  T.it("a new character sees the setup once; Done keeps it closed next time", function()
    local game = mock.new()
    local ns = game:loadAddon()
    game:login()
    T.ok(ns.Setup.frame and ns.Setup.frame:IsShown(), "shown for a fresh character")
    ns.Setup.frame:Hide()
    ns.Setup:Settings().done = true
    game:login()
    game:advance(5)
    T.no(ns.Setup.frame:IsShown())
    T.eq(#ns.Errors.list, 0)
  end)

  T.it("feature groups turn their modules off and on", function()
    local game = mock.new()
    local ns = game:loadAddon()
    game:login()
    local g = ns.Setup.GROUPS[6]
    ns.Setup:SetGroup(g, false)
    T.no(ns.Modules:Get("Chat").enabled)
    T.no(ns.Setup:GroupOn(g))
    ns.Setup:SetGroup(g, true)
    T.ok(ns.Modules:Get("SpellCheck").enabled)
  end)

  T.it("accessibility applies at login: bigger text, colorblind colors, no fading", function()
    local game = mock.new()
    local ns = game:loadAddon()
    game:login()
    game:slash("access font 1.5")
    game:slash("access colorblind on")
    game:slash("access motion off")
    ns.Theme:ApplyAccessibility()
    T.eq(ns.Theme.font.normal, 18)
    T.same({ ns.Theme:Color("good") }, { 0.35, 0.65, 1.00, 1 })
    T.ok(ns.Theme.reducedMotion)
    ns.Toast:Show({ title = "x", duration = 1 })
    game:advance(1.1)
    T.eq(ns.Toast:Count(), 0, "gone at once, no fade")
  end)
end)
