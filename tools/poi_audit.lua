-- tools/poi_audit.lua <SavedVariables\Outrider.lua> <out.md>
-- How right are Outrider's map places? (Gary, 2026-11-21: "we need to true up
-- all of our poi locations".) Ground truth = NPCs Gary's characters talked to
-- or stood next to (POICapture places, Discovery interact/near). Each source is
-- measured against it:
--   pack   private/Outrider_Data_NPC (QuestieDB, Classic coordinates)
--   guide  Data/Leveling*.lua (Wowhead's Forever guides)
-- A spot more than OFF (map share) away from the truth counts as wrong.
-- Also lists where pack and guide disagree with no truth yet (go and look).
-- Reads only; writes the report file.

local SV, OUT = arg[1], arg[2] or "docs/POI_AUDIT.md"
local OFF = 0.03

local function loadInto(path, env)
  local chunk = assert(loadfile(path))
  setfenv(chunk, env)
  return chunk
end

-- 1. Gary's saved data
local sv = {}
loadInto(SV, sv)()
local g = sv.Outrider_DB and sv.Outrider_DB.global or {}

-- 2. the NPC pack
local pk = {}
loadInto("private/Outrider_Data_NPC/Data.lua", pk)()
local packByNpc, packByName = {}, {}
for mapID, rows in pairs(pk.Outrider_DataNPC and pk.Outrider_DataNPC.maps or {}) do
  for _, r in ipairs(rows) do
    local e = { mapID = mapID, x = r[3], y = r[4], name = r[5], title = r[6], npcID = r[1] }
    packByNpc[r[1]] = packByNpc[r[1]] or {}
    table.insert(packByNpc[r[1]], e)
    if r[5] then packByName[r[5]] = packByName[r[5]] or e end
  end
end

-- 3. the guide places (a fake ns that only collects registrations)
local guideByName = {}
local ns = { Data = { Register = function(_, kind, _, list)
  if kind ~= "place" then return end
  for _, e in ipairs(list) do if e.name then guideByName[e.name] = guideByName[e.name] or e end end
end }, Leveling = {} }
for _, f in ipairs({ "Leveling", "Leveling_Places", "Leveling_DungeonQuests" }) do
  local env = setmetatable({}, { __index = _G })
  loadInto("addon/Outrider/Data/" .. f .. ".lua", env)("Outrider", ns)
end

-- ground truth: one spot per NPC, the best Gary has
local truth = {}
for _, p in pairs(g.pois or {}) do
  if type(p) == "table" and p.npcID and p.mapID and p.x and p.source ~= "client" then
    truth[p.npcID] = { name = p.name, mapID = p.mapID, x = p.x, y = p.y, how = "talked to (" .. tostring(p.kind) .. ")" }
  end
end
for npcID, e in pairs(g.discovered and g.discovered.npcs or {}) do
  if type(e) == "table" and (e.qualityRank or 0) >= 3 and e.mapID and e.x and not truth[npcID] then
    truth[npcID] = { name = e.name, mapID = e.mapID, x = e.x, y = e.y, how = tostring(e.quality) }
  end
end

local function off(a, b) return math.max(math.abs(a.x - b.x), math.abs(a.y - b.y)) end
local function pct(v) return string.format("%.1f", v * 100) end

local stats = { truth = 0, pack = { n = 0, bad = 0, other = 0 }, guide = { n = 0, bad = 0 } }
local wrong = {}
for npcID, t in pairs(truth) do
  stats.truth = stats.truth + 1
  -- the pack: same NPC on the same map
  local rows = packByNpc[npcID]
  if rows then
    local same
    for _, r in ipairs(rows) do if r.mapID == t.mapID then same = r end end
    if same then
      stats.pack.n = stats.pack.n + 1
      local d = off(same, t)
      if d > OFF then
        stats.pack.bad = stats.pack.bad + 1
        wrong[#wrong + 1] = string.format("| %s | pack | %s, %s | %s, %s | %s |", tostring(t.name), pct(same.x), pct(same.y), pct(t.x), pct(t.y), pct(d))
      end
    else
      stats.pack.other = stats.pack.other + 1
      wrong[#wrong + 1] = string.format("| %s | pack | on map %s | on map %s | other zone |", tostring(t.name), tostring(rows[1].mapID), tostring(t.mapID))
    end
  end
  -- the guide, by name
  local gd = t.name and guideByName[t.name]
  if gd then
    stats.guide.n = stats.guide.n + 1
    local d = off(gd, t)
    if d > OFF then
      stats.guide.bad = stats.guide.bad + 1
      wrong[#wrong + 1] = string.format("| %s | guide (%s) | %s, %s | %s, %s | %s |", tostring(t.name), tostring(gd.zone), pct(gd.x), pct(gd.y), pct(t.x), pct(t.y), pct(d))
    end
  end
end
table.sort(wrong)

-- pack and guide disagree where Gary hasn't been yet
local disagree, both = {}, 0
for name, gd in pairs(guideByName) do
  local p = packByName[name]
  if p then
    both = both + 1
    local d = off(p, gd)
    if d > OFF then disagree[#disagree + 1] = string.format("| %s | %s | %s, %s | %s, %s | %s |", name, tostring(gd.zone), pct(p.x), pct(p.y), pct(gd.x), pct(gd.y), pct(d)) end
  end
end
table.sort(disagree)

local f = assert(io.open(OUT, "w"))
local function w(s) f:write(s, "\n") end
w("# Map places audit")
w("")
w("Generated by `python tools/lua.py tools/poi_audit.lua <SavedVariables\\Outrider.lua>`. Truth = NPCs Gary's characters talked to or stood next to.")
w(string.format("A spot more than %s%% of the map away from the truth counts as wrong.", pct(OFF)))
w("")
w(string.format("- NPCs with a true spot: %d", stats.truth))
w(string.format("- NPC pack (QuestieDB, Classic): %d checked on the same map, %d wrong (%s%%); %d listed on another map", stats.pack.n, stats.pack.bad,
  stats.pack.n > 0 and string.format("%.0f", stats.pack.bad / stats.pack.n * 100) or "-", stats.pack.other))
w(string.format("- Guides (Wowhead Forever): %d checked, %d wrong (%s%%)", stats.guide.n, stats.guide.bad,
  stats.guide.n > 0 and string.format("%.0f", stats.guide.bad / stats.guide.n * 100) or "-"))
w(string.format("- Pack and guide both list %d NPCs; they disagree on %d (no truth yet)", both, #disagree))
w("")
w("In game your own sighting always wins: these numbers say which source to trust where you haven't been.")
w("")
w("## Wrong against the truth")
w("")
w("| NPC | source | source says | truth | off by (% of map) |")
w("|---|---|---|---|---|")
for _, l in ipairs(wrong) do w(l) end
w("")
w("## Pack and guide disagree (nobody has checked)")
w("")
w("| NPC | zone | pack | guide | apart (% of map) |")
w("|---|---|---|---|---|")
for _, l in ipairs(disagree) do w(l) end
f:close()
print(string.format("truth %d | pack %d checked, %d wrong, %d other map | guide %d checked, %d wrong | disagree %d of %d",
  stats.truth, stats.pack.n, stats.pack.bad, stats.pack.other, stats.guide.n, stats.guide.bad, #disagree, both))
