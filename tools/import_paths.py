"""tools/import_paths.py -- walked routes for the way-there dots, from QuestieDB.

QuestieDB gives many NPCs and creatures a patrol route (NPC field 8: the points
they walk, per zone). Guards walk roads and gates, creatures walk trails and
cave mouths, so these routes are real walkable ground. The Path module joins
them with your own breadcrumbs when it plans the dots to a destination
(Gary, 2026-11-21: "I need to get to that quest marker but have no clue where
to go ... find the best path to the entrance").
Writes private/Outrider_Data_Paths, a load-on-demand data addon (GPLv3, D20/D21).

Usage:  py tools/import_paths.py [path\\to\\QuestieDB]
Community data, verified = false. Zones without patrols (Dun Morogh, Zephras
Isle, 2026-11-21) get nothing here; your own walking fills them in.
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import import_questie as q
import import_mobs as mobs

OUT = os.path.join(q.ROOT, "private", "Outrider_Data_Paths")
MIN_POINTS = 3   # a route needs at least this many points to be worth a line


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    cfg = json.load(open(os.path.join(q.ROOT, "tools", "local.json"), encoding="utf-8-sig"))
    qdb = mobs.find_questiedb(args, cfg)
    meta, get = q.read_meta(os.path.join(qdb, "QuestieDB_Forever.toc"))
    area_map = q.read_area_map(qdb)
    version = meta.get("X-BUILD-COMMIT", "?")
    by_map, routes, points = {}, 0, 0
    for k in sorted(k for k in meta if re.match(r"^X-Npc-\d+-8$", k)):
        v = q.cbor(get(k))
        if not isinstance(v, dict):
            continue
        for area, paths in v.items():
            ui = area_map.get(area)
            if not ui:
                continue
            for path in q.lua_array(paths):
                line = []
                for p in q.lua_array(path):
                    p = q.lua_array(p)
                    if len(p) >= 2 and p[0] is not None and 0 <= p[0] <= 100 and 0 <= p[1] <= 100:
                        line.append((p[0] / 100.0, p[1] / 100.0))
                if len(line) >= MIN_POINTS:
                    by_map.setdefault(ui, []).append(line)
                    routes += 1
                    points += len(line)
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "Outrider_Data_Paths.toc"), "w", encoding="utf-8", newline="\r\n") as f:
        f.write("## Interface: 16001\n## Title: Outrider Data: walked routes\n")
        f.write("## Notes: NPC patrol routes used as walkable ground, converted from QuestieDB (GPLv3, see LICENSE-DATA.txt).\n")
        f.write("## LoadOnDemand: 1\n## X-Source: QuestieDB %s\n\nData.lua\n" % version)
    with open(os.path.join(OUT, "Data.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("-- GENERATED by tools/import_paths.py from QuestieDB %s.\n" % version)
        f.write("-- Source: QuestieDB (https://github.com/Questie/Questie), GPLv3 per its LICENSE.md.\n")
        f.write("-- maps[uiMapID] = { {x,y,x,y,...} per patrol route }; map fractions. verified = false.\n")
        f.write("Outrider_DataPaths = { source = %s, maps = {\n" % q.lua_str("QuestieDB " + version))
        for ui in sorted(by_map):
            f.write("[%d]={\n" % ui)
            for line in by_map[ui]:
                f.write("{%s},\n" % ",".join("%.4f,%.4f" % p for p in line))
            f.write("},\n")
        f.write("} }\n")
    size = os.path.getsize(os.path.join(OUT, "Data.lua"))
    print("routes %d, points %d on %d maps, Data.lua %d KB" % (routes, points, len(by_map), size // 1024))


if __name__ == "__main__":
    main()
