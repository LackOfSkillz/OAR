-- tools/build_fight_plans.lua
-- Turns docs/fight_macro_catalog_draft.lua (research, 2026-11-18) into the lean
-- data pack the addon loads: addon/Outrider/Data/FightPlans.lua. Keeps what the
-- macro builder needs (talent trees, key names, level brackets with their
-- lines, spells and keep order, utility keys per race); drops the printed
-- example macros and the learn table. Each class is wrapped in a loader, so a
-- character only builds its own class's tables.
-- Run: python tools/lua.py tools/build_fight_plans.lua
local src = "docs/fight_macro_catalog_draft.lua"
local out = "addon/Outrider/Data/FightPlans.lua"
local catalog = assert(loadfile(src))()

local NL = string.char(10)
local function q(s)
  return (string.format("%q", tostring(s)):gsub("\\" .. NL, "\\n"))
end
local buf = {}
local function w(s) buf[#buf + 1] = s end
local function line(s) w(s .. NL) end

line("-- Data/FightPlans.lua  GENERATED by tools/build_fight_plans.lua from")
line("-- docs/fight_macro_catalog_draft.lua. Do not edit by hand: edit the draft and rebuild.")
line("-- Fight macro plans per class x talent spec x pve/pvp x key, by level bracket.")
line("-- verified = false: Forever community guides and Classic Era sources (see the research doc).")
line("local _, ns = ...")
line("ns.FightPlans = { verified = false, date = " .. q(catalog.date or "") .. ", loaders = {} }")
line("local P = ns.FightPlans")
line("-- A class's tables are built the first time it's asked for.")
line("function P:Class(cls)")
line("  if self[cls] == nil and self.loaders[cls] then self[cls] = self.loaders[cls]() or false end")
line("  return self[cls] or nil")
line("end")

local CLASSES = { "HUNTER", "PRIEST", "MAGE", "WARRIOR", "ROGUE", "WARLOCK", "DRUID", "PALADIN", "SHAMAN" }
local slots = 0
for _, cls in ipairs(CLASSES) do
  local c = catalog[cls]
  if c then
    line("P.loaders." .. cls .. " = function()")
    local trees = {}
    for _, v in ipairs(c.trees or {}) do trees[#trees + 1] = q(v) end
    local kk = {}
    for k in pairs(c.keys or {}) do kk[#kk + 1] = k end
    table.sort(kk)
    local keys = {}
    for _, k in ipairs(kk) do keys[#keys + 1] = k .. " = " .. q(c.keys[k]) end
    line("local C = { trees = { " .. table.concat(trees, ", ") .. " }, keys = { " .. table.concat(keys, ", ") .. " }, specs = {}, utility = {} }")
    local specNames = {}
    for s in pairs(c.specs or {}) do specNames[#specNames + 1] = s end
    table.sort(specNames)
    for _, spec in ipairs(specNames) do
      line("C.specs[" .. q(spec) .. "] = {")
      for _, mode in ipairs({ "pve", "pvp" }) do
        local m = c.specs[spec][mode]
        if m and m.brackets then
          line("  " .. mode .. " = {")
          local keyNames = {}
          for k in pairs(m.brackets) do keyNames[#keyNames + 1] = k end
          table.sort(keyNames)
          for _, key in ipairs(keyNames) do
            line("    " .. key .. " = {")
            for _, b in ipairs(m.brackets[key]) do
              line("      { from = " .. tonumber(b.from) .. ", slots = {")
              for _, sl in ipairs(b.slots) do
                slots = slots + 1
                if type(sl) == "string" then
                  line("        " .. q(sl) .. ",")
                else
                  local sp = {}
                  for _, n in ipairs(sl.spells or {}) do sp[#sp + 1] = q(n) end
                  line("        { line = " .. q(sl.line) .. ", spells = { " .. table.concat(sp, ", ") .. " }, kind = "
                    .. q(sl.kind or "filler") .. ", keep = " .. (tonumber(sl.keep) or 5) .. ", why = " .. q(sl.why or "") .. " },")
                end
              end
              line("      } },")
            end
            line("    },")
          end
          line("  },")
        end
      end
      line("}")
    end
    for _, u in ipairs((catalog.utility or {})[cls] or {}) do
      line("table.insert(C.utility, { id = " .. q(u.id or "") .. ", name = " .. q(u.name or "") .. ", text = " .. q(u.text or "")
        .. ", why = " .. q(u.why or "") .. ", race = " .. (u.race and q(u.race) or "nil") .. ", spec = " .. (u.spec and q(u.spec) or "nil") .. " })")
    end
    line("return C")
    line("end")
  end
end
local f = assert(io.open(out, "w"))
f:write(table.concat(buf))
f:close()
print(("wrote %s: %d slots, %d bytes"):format(out, slots, #table.concat(buf)))
