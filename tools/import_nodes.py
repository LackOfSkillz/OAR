"""tools/import_nodes.py -- herb and ore spawn points from Questie's Forever data (decision D10/D11).

Gary (2026-11-13): "pull the node map into our database". QuestieDB's Forever
objects already carry every herb and ore node with its spawn points per zone,
in Forever's own areas (Zephras Isle included), so no other source is needed.
Writes private/Outrider_Data_Nodes (git-ignored, never released).

Usage:  py tools/import_nodes.py [path\\to\\QuestieDB] [--deploy]
Every point is community data, verified = false until Gary gathers there.
"""
import json, os, re, shutil, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import import_questie as q
import import_mobs as mobs

OUT = os.path.join(q.ROOT, "private", "Outrider_Data_Nodes")
HERBS = {"Peacebloom", "Silverleaf", "Earthroot", "Mageroyal", "Briarthorn", "Stranglekelp", "Bruiseweed",
         "Wild Steelbloom", "Kingsblood", "Liferoot", "Fadeleaf", "Goldthorn", "Khadgar's Whisker", "Firebloom",
         "Purple Lotus", "Sungrass", "Gromsblood", "Golden Sansam", "Dreamfoil", "Mountain Silversage",
         "Plaguebloom", "Icecap", "Black Lotus", "Grave Moss", "Wintersbite", "Arthas' Tears", "Blindweed",
         "Ghost Mushroom", "Marefoil", "Demonsage", "Death Lotus", "Frilled Lichen", "Rosecap", "Stranglevine"}


def kind_of(name):
    if name in HERBS:
        return "herb"
    if name.endswith(" Vein") or name.endswith(" Deposit"):
        return "ore"
    return None


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    cfg = json.load(open(os.path.join(q.ROOT, "tools", "local.json"), encoding="utf-8-sig"))
    qdb = mobs.find_questiedb(args, cfg)
    meta, get = q.read_meta(os.path.join(qdb, "QuestieDB_Forever.toc"))
    area_map = q.read_area_map(qdb)
    version = meta.get("X-BUILD-COMMIT", "?")
    oids = sorted({int(m.group(1)) for k in meta for m in [re.match(r"^X-Object-(\d+)-S$", k)] if m})
    by_map, total = {}, 0
    for oid in oids:
        row = q.cbor(get("X-Object-%d-S" % oid))
        if not isinstance(row, dict) or not row.get(1):
            continue
        name = row[1]
        kind = kind_of(name)
        raw = kind and get("X-Object-%d-4" % oid)
        if not raw:
            continue
        spawns = q.cbor(raw)
        for area, pts in (spawns.items() if isinstance(spawns, dict) else []):
            ui = area_map.get(area)
            if not ui:
                continue
            points = []
            for p in q.lua_array(pts):
                p = q.lua_array(p)
                if len(p) >= 2 and p[0] is not None and 0 <= p[0] <= 100 and 0 <= p[1] <= 100:
                    points.append((p[0] / 100.0, p[1] / 100.0))
            if points:
                entry = by_map.setdefault(ui, {}).setdefault((name, kind), [])
                entry.extend(points)
                total += len(points)
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "Outrider_Data_Nodes.toc"), "w", encoding="utf-8", newline="\r\n") as f:
        f.write("## Interface: 16001\n## Title: Outrider Data: herb and ore nodes (private)\n")
        f.write("## Notes: Private copy of node spawns from QuestieDB (GPLv3, see Outrider DECISIONS D10). Not for redistribution.\n")
        f.write("## LoadOnDemand: 1\n## X-Source: QuestieDB %s\n\nData.lua\n" % version)
    with open(os.path.join(OUT, "Data.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("-- GENERATED by tools/import_nodes.py from QuestieDB %s. Private copy (D10), do not redistribute.\n" % version)
        f.write("-- Source: QuestieDB (https://github.com/Questie/Questie), GPLv3 per its LICENSE.md.\n")
        f.write("-- { name, kind (herb|ore), {x,y,x,y,...} } per uiMapID; map fractions. verified = false.\n")
        f.write("Outrider_DataNodes = { source = %s, maps = {\n" % q.lua_str("QuestieDB " + version))
        for ui in sorted(by_map):
            f.write("[%d]={\n" % ui)
            for (name, kind), pts in sorted(by_map[ui].items()):
                f.write("{%s,%s,{%s}},\n" % (q.lua_str(name), q.lua_str(kind), ",".join("%.3f,%.3f" % p for p in pts)))
            f.write("},\n")
        f.write("} }\n")
    size = os.path.getsize(os.path.join(OUT, "Data.lua"))
    print("node points %d on %d maps, Data.lua %d KB (Zephras Isle 2521: %d points)" % (
        total, len(by_map), size // 1024, sum(len(v) for v in by_map.get(2521, {}).values())))
    if "--deploy" in sys.argv:
        target = os.path.join(cfg["addonsDir"], "Outrider_Data_Nodes")
        if os.path.exists(target):
            shutil.rmtree(target)
        shutil.copytree(OUT, target)
        print("deployed to", target)


if __name__ == "__main__":
    main()
