"""tools/import_map_overlays.py - build addon/Outrider/Data/MapOverlays.lua

The world map's unexplored areas (Gary, 2026-11-17: "fetch it"): the game's
own WorldMapOverlay, WorldMapOverlayTile and UiMapXMapArt tables, as CSV from
wago.tools for the exact WoW Forever build, joined into one Lua table:

    ns.MapOverlays = { build = "...", [uiMapID] = { {w, h, x, y, {fileDataID, ...}}, ... } }

Tile ids are row-major (row 0 left to right, then row 1...), the order the
client's own exploration overlay uses. Only overlays of maps that have art
(UiMapXMapArt, phase 0) are kept.

Fetch (asks the network, so only with Gary's OK):
    curl "https://wago.tools/db2/<Table>/csv?build=<build>" -o <Table>.csv
Then:
    python tools/import_map_overlays.py <folder with the 3 csv files> <build>
"""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "addon", "Outrider", "Data", "MapOverlays.lua")


def rows(folder, name):
    with open(os.path.join(folder, name + ".csv"), newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    folder, build = sys.argv[1], sys.argv[2]
    art_to_map = {}
    for r in rows(folder, "UiMapXMapArt"):
        if r["PhaseID"] == "0":
            art_to_map.setdefault(int(r["UiMapArtID"]), []).append(int(r["UiMapID"]))
    tiles = {}
    for r in rows(folder, "WorldMapOverlayTile"):
        if r["LayerIndex"] != "0":
            continue
        tiles.setdefault(int(r["WorldMapOverlayID"]), []).append((int(r["RowIndex"]), int(r["ColIndex"]), int(r["FileDataID"])))
    maps = {}
    kept = skipped = 0
    for r in rows(folder, "WorldMapOverlay"):
        art, oid = int(r["UiMapArtID"]), int(r["ID"])
        if art not in art_to_map or oid not in tiles:
            skipped += 1
            continue
        ids = [fid for _, _, fid in sorted(tiles[oid])]
        entry = (int(r["TextureWidth"]), int(r["TextureHeight"]), int(r["OffsetX"]), int(r["OffsetY"]), ids)
        for m in art_to_map[art]:
            maps.setdefault(m, []).append(entry)
        kept += 1
    lines = [
        "-- Data/MapOverlays.lua (generated by tools/import_map_overlays.py, do not edit)",
        "-- The world map's explorable areas for WoW Forever build %s: the game's own" % build,
        "-- WorldMapOverlay, WorldMapOverlayTile and UiMapXMapArt tables, read from",
        "-- wago.tools (client data, fetched with Gary's OK 2026-11-17). MapReveal draws",
        "-- the ones a character hasn't explored. { [uiMapID] = { {w, h, x, y, {fileDataIDs row by row}} } }",
        "local _, ns = ...",
        'ns.MapOverlays = { build = "%s", maps = {' % build,
    ]
    for m in sorted(maps):
        parts = ["{%d,%d,%d,%d,{%s}}" % (w, h, x, y, ",".join(str(i) for i in ids)) for (w, h, x, y, ids) in maps[m]]
        lines.append("  [%d] = { %s }," % (m, ", ".join(parts)))
    lines.append("} }")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d maps, %d overlays (%d skipped: no map art)" % (os.path.relpath(OUT, ROOT), len(maps), kept, skipped))
    return 0


if __name__ == "__main__":
    sys.exit(main())
