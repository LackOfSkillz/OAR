"""Build addon/Outrider/Data/VanguardFacts.lua from tools/vanguard_facts/*.frag.

Researched facts (sources: docs/vanguard/VANGUARD_FACTS_SOURCES.md). Edit the
fragments, then run:  python tools/build_vanguard_facts.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "addon", "Outrider", "Data", "VanguardFacts.lua")
PARTS = ["raids", "access", "bosses_a", "bosses_b", "prices", "enchants"]
HEAD = '''-- Data/VanguardFacts.lua  GENERATED by tools/build_vanguard_facts.py from
-- tools/vanguard_facts/*.frag (web research 2026-11-26, Gary asked for it).
-- Facts only, in our own words; every row names its source.
-- verified = false: nothing here has been seen in game on WoW Forever yet.
--   bosses[instance]  = { kind = "forever" | "classic", source, list = { {name, npc?, tags = {tag = reason}} } }
--                       kind "classic": a Classic-based guide for a dungeon Forever didn't change (Forever may differ)
--   access[instance]  = { needs = none | key | attunement | quest, who = one | each, item?, itemName?, quest?, note?, conflict? }
--   raids[name]       = { size?, min?, max?, status, note?, roles? }
--   prices[itemID]    = { name, copper, per, reqLevel?, kind, source }  vendor buy price
--   enchants[id]      = { name, stats = { token = n } } or { name, proc = true }, source
-- Do not hand-edit: edit the fragments and rebuild.
local _, ns = ...
local F = { version = "2026-11-26", verified = false, bosses = {}, access = {}, raids = {}, prices = {}, enchants = {} }
'''


def main():
    body = [HEAD]
    for p in PARTS:
        path = os.path.join(ROOT, "tools", "vanguard_facts", p + ".frag")
        if not os.path.exists(path):
            sys.exit("missing fragment: " + path)
        body.append("do\n" + open(path, encoding="utf-8").read().rstrip() + "\nend\n")
    body.append("ns.VanguardFacts = F\n")
    open(OUT, "w", encoding="utf-8").write("\n".join(body))
    print("wrote", OUT, "from", len(PARTS), "fragments")


if __name__ == "__main__":
    main()
