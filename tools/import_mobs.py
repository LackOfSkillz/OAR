"""tools/import_mobs.py -- private copy of Questie's creatures (decision D10, like import_questie.py).

Every NPC that is hostile to both factions (no friendlyToFaction) and has spawn
points: name, level range, rank (rare, elite...) and up to 4 spread-out spawn
points per map. Feeds the Journey finder's "creatures" and "rares" (Gary,
2026-11-13: "a critter I want to hunt", "use available data, not only places
I know"). Writes private/Outrider_Data_Mobs (git-ignored, never released).

Usage:  py tools/import_mobs.py [path\\to\\QuestieDB] [--deploy]
Every entry is community data, verified = false until seen in game.
"""
import json, os, re, shutil, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import import_questie as q

OUT = os.path.join(q.ROOT, "private", "Outrider_Data_Mobs")
SPAWNS_BIT = 2 ** (7 - 1)
MAX_POINTS = 4


def spread(points, n):
    """Up to n points: the first, then each time the one farthest from those kept."""
    if len(points) <= n:
        return points
    keep = [points[0]]
    while len(keep) < n:
        best, bd = None, -1
        for p in points:
            d = min((p[0] - k[0]) ** 2 + (p[1] - k[1]) ** 2 for k in keep)
            if d > bd:
                best, bd = p, d
        keep.append(best)
    return keep


def find_questiedb(args, cfg):
    path = args[0] if args else os.path.join(cfg["addonsDir"], "QuestieDB")
    if os.path.isdir(path):
        return path
    import glob, tempfile, zipfile
    zips = sorted(glob.glob(os.path.join(q.ROOT, "private", "questie-source", "Questie-*.zip")))
    if not zips:
        sys.exit("No QuestieDB installed and no saved Questie zip in private/questie-source")
    tmp = tempfile.mkdtemp(prefix="questiedb_")
    with zipfile.ZipFile(zips[-1]) as z:
        for name in z.namelist():
            if name.startswith("QuestieDB/") and (name.endswith("QuestieDB_Forever.toc") or "/support/Forever/Zones/" in name):
                z.extract(name, tmp)
    print("using saved download", os.path.basename(zips[-1]))
    return os.path.join(tmp, "QuestieDB")


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    cfg = json.load(open(os.path.join(q.ROOT, "tools", "local.json"), encoding="utf-8-sig"))
    qdb = find_questiedb(args, cfg)
    meta, get = q.read_meta(os.path.join(qdb, "QuestieDB_Forever.toc"))
    area_map = q.read_area_map(qdb)
    version = meta.get("X-BUILD-COMMIT", "?")
    ids = sorted({int(m.group(1)) for k in meta for m in [re.match(r"^X-Npc-(\d+)-S$", k)] if m})
    by_map, kept, rares = {}, 0, 0
    for nid in ids:
        row = q.cbor(get("X-Npc-%d-S" % nid))
        if not isinstance(row, dict) or row.get(13) or not row.get(1):
            continue  # friendly to a faction (town folk), or no name
        if not (row.get("p", 0) // SPAWNS_BIT) % 2:
            continue
        spawns = q.cbor(get("X-Npc-%d-7" % nid))
        if not isinstance(spawns, dict):
            continue
        lo, hi, rank = row.get(4) or 0, row.get(5) or row.get(4) or 0, row.get(6) or 0
        for area, pts in spawns.items():
            ui = area_map.get(area)
            if not ui:
                continue
            points = []
            for p in q.lua_array(pts):
                p = q.lua_array(p)
                if len(p) >= 2 and p[0] is not None and 0 <= p[0] <= 100 and 0 <= p[1] <= 100:
                    points.append((p[0] / 100.0, p[1] / 100.0))
            if not points:
                continue
            by_map.setdefault(ui, []).append((nid, row[1], lo, hi, rank, spread(points, MAX_POINTS)))
            kept += 1
            if rank in (2, 4):
                rares += 1
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "Outrider_Data_Mobs.toc"), "w", encoding="utf-8", newline="\r\n") as f:
        f.write("## Interface: 16001\n## Title: Outrider Data: creatures (private)\n")
        f.write("## Notes: Private copy of creatures from QuestieDB (GPLv3, see Outrider DECISIONS D10). Not for redistribution.\n")
        f.write("## LoadOnDemand: 1\n## X-Source: QuestieDB %s\n\nData.lua\n" % version)
        # resistances / immunities / spells from tools/import_mob_res.py (smart loadout)
        if os.path.exists(os.path.join(OUT, "Res.lua")):
            f.write("Res.lua\n")
    with open(os.path.join(OUT, "Data.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("-- GENERATED by tools/import_mobs.py from QuestieDB %s. Private copy (D10), do not redistribute.\n" % version)
        f.write("-- Source: QuestieDB (https://github.com/Questie/Questie), GPLv3 per its LICENSE.md.\n")
        f.write("-- { npcID, name, minLevel, maxLevel, rank (0 normal, 1 elite, 2 rare elite, 3 boss, 4 rare), {x,y,...} } per uiMapID. verified = false.\n")
        f.write("Outrider_DataMobs = { source = %s, maps = {\n" % q.lua_str("QuestieDB " + version))
        for ui in sorted(by_map):
            f.write("[%d]={\n" % ui)
            for nid, name, lo, hi, rank, pts in by_map[ui]:
                f.write("{%d,%s,%d,%d,%d,{%s}},\n" % (nid, q.lua_str(name), lo, hi, rank,
                                                     ",".join("%.4f,%.4f" % p for p in pts)))
            f.write("},\n")
        f.write("} }\n")
    size = os.path.getsize(os.path.join(OUT, "Data.lua"))
    print("NPCs scanned %d, creatures kept %d (rares %d) on %d maps, Data.lua %d KB"
          % (len(ids), kept, rares, len(by_map), size // 1024))
    if "--deploy" in sys.argv:
        target = os.path.join(cfg["addonsDir"], "Outrider_Data_Mobs")
        if os.path.exists(target):
            shutil.rmtree(target)
        shutil.copytree(OUT, target)
        print("deployed to", target)


if __name__ == "__main__":
    main()
