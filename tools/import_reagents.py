"""tools/import_reagents.py -- where to get crafting ingredients, from QuestieDB.

For every trade good (item class 7: herbs, ore, leather, cloth, meat, spices,
thread, vials...) the sources QuestieDB lists:
  drops   - creatures that drop it (field 2), with level range and spawns
  nodes   - objects that give it (field 3: herb and ore nodes, chests), with spawns
  vendors - NPCs that sell it (field 14), with their faction and spawns
Feeds the Professions page (Gary, 2026-11-21: "directs them to either the
auction house or the closest places on the map in their level range to acquire
the ingredients"). Writes private/Outrider_Data_Reagents, a load-on-demand data
addon shipped like the other QuestieDB packs (GPLv3, D20/D21).

Usage:  py tools/import_reagents.py [path\\to\\QuestieDB] [--deploy]
Every entry is community data, verified = false until seen in game.
"""
import json, os, re, shutil, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import import_questie as q
import import_mobs as mobs

OUT = os.path.join(q.ROOT, "private", "Outrider_Data_Reagents")
TRADE_GOODS = 7
MAX_DROPS = 15        # creatures kept per item (QuestieDB lists hundreds for ore and cloth)
MAX_VENDORS = 30
MAX_NODES = 12
MAX_POINTS = 3        # spawn points kept per map
FACTION = {"A": "A", "H": "H", "AH": None}


def ids_of(v):
    return [x for x in q.lua_array(v) if isinstance(x, int)] if not isinstance(v, int) else [v]


def spawns_of(raw, area_map):
    out = {}
    spawns = q.cbor(raw) if raw else None
    for area, pts in (spawns.items() if isinstance(spawns, dict) else []):
        ui = area_map.get(area)
        if not ui:
            continue
        points = []
        for p in q.lua_array(pts):
            p = q.lua_array(p)
            if len(p) >= 2 and p[0] is not None and 0 <= p[0] <= 100 and 0 <= p[1] <= 100:
                points.append((p[0] / 100.0, p[1] / 100.0))
        if points:
            out.setdefault(ui, []).extend(points)
    return {ui: mobs.spread(pts, MAX_POINTS) for ui, pts in out.items()}


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    cfg = json.load(open(os.path.join(q.ROOT, "tools", "local.json"), encoding="utf-8-sig"))
    qdb = mobs.find_questiedb(args, cfg)
    meta, get = q.read_meta(os.path.join(qdb, "QuestieDB_Forever.toc"))
    area_map = q.read_area_map(qdb)
    version = meta.get("X-BUILD-COMMIT", "?")
    item_ids = sorted({int(m.group(1)) for k in meta for m in [re.match(r"^X-Item-(\d+)-S$", k)] if m})

    items, npcs, objects = {}, {}, {}

    def npc(nid):
        if nid in npcs:
            return npcs[nid] is not None
        row = q.cbor(get("X-Npc-%d-S" % nid)) if get("X-Npc-%d-S" % nid) else None
        sp = spawns_of(get("X-Npc-%d-7" % nid), area_map) if isinstance(row, dict) else {}
        if not isinstance(row, dict) or not row.get(1) or not sp:
            npcs[nid] = None
            return False
        lo = row.get(4) or 0
        npcs[nid] = (row[1], lo, row.get(5) or lo, FACTION.get(row.get(13)), sp)
        return True

    def obj(oid):
        if oid in objects:
            return objects[oid] is not None
        row = q.cbor(get("X-Object-%d-S" % oid)) if get("X-Object-%d-S" % oid) else None
        sp = spawns_of(get("X-Object-%d-4" % oid), area_map) if isinstance(row, dict) else {}
        if not isinstance(row, dict) or not row.get(1) or not sp:
            objects[oid] = None
            return False
        objects[oid] = (row[1], sp)
        return True

    for iid in item_ids:
        row = q.cbor(get("X-Item-%d-S" % iid))
        if not isinstance(row, dict) or row.get(12) != TRADE_GOODS or not row.get(1):
            continue
        drops = [n for n in ids_of(q.cbor(get("X-Item-%d-2" % iid))) if npc(n)][:MAX_DROPS] if get("X-Item-%d-2" % iid) else []
        nodes = [o for o in ids_of(q.cbor(get("X-Item-%d-3" % iid))) if obj(o)][:MAX_NODES] if get("X-Item-%d-3" % iid) else []
        vendors = [n for n in ids_of(q.cbor(get("X-Item-%d-14" % iid))) if npc(n)][:MAX_VENDORS] if get("X-Item-%d-14" % iid) else []
        items[iid] = (row[1], row.get(9) or 0, row.get(13) or 0, drops, nodes, vendors)

    def pts(sp):
        return ",".join("[%d]={%s}" % (ui, ",".join("%.3f,%.3f" % p for p in ps)) for ui, ps in sorted(sp.items()))

    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "Outrider_Data_Reagents.toc"), "w", encoding="utf-8", newline="\r\n") as f:
        f.write("## Interface: 16001\n## Title: Outrider Data: crafting ingredients\n")
        f.write("## Notes: Where to get crafting ingredients, converted from QuestieDB (GPLv3, see LICENSE-DATA.txt).\n")
        f.write("## LoadOnDemand: 1\n## X-Source: QuestieDB %s\n\nData.lua\n" % version)
    with open(os.path.join(OUT, "Data.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("-- GENERATED by tools/import_reagents.py from QuestieDB %s.\n" % version)
        f.write("-- Source: QuestieDB (https://github.com/Questie/Questie), GPLv3 per its LICENSE.md.\n")
        f.write("-- items[itemID] = { name, itemLevel, subclass, {drop npcIDs}, {node objectIDs}, {vendor npcIDs} }\n")
        f.write("-- npcs[npcID] = { name, minLevel, maxLevel, faction (\"A\"/\"H\"/nil), { [uiMapID] = {x,y,...} } }\n")
        f.write("-- objects[objectID] = { name, { [uiMapID] = {x,y,...} } }. Map fractions. verified = false.\n")
        f.write("Outrider_DataReagents = { source = %s,\n" % q.lua_str("QuestieDB " + version))
        f.write("items = {\n")
        for iid in sorted(items):
            name, ilvl, sub, drops, nodes, vendors = items[iid]
            f.write("[%d]={%s,%d,%d,{%s},{%s},{%s}},\n" % (iid, q.lua_str(name), ilvl, sub,
                    ",".join(map(str, drops)), ",".join(map(str, nodes)), ",".join(map(str, vendors))))
        f.write("},\nnpcs = {\n")
        for nid in sorted(n for n, v in npcs.items() if v):
            name, lo, hi, fac, sp = npcs[nid]
            f.write("[%d]={%s,%d,%d,%s,{%s}},\n" % (nid, q.lua_str(name), lo, hi, q.lua_str(fac) if fac else "nil", pts(sp)))
        f.write("},\nobjects = {\n")
        for oid in sorted(o for o, v in objects.items() if v):
            name, sp = objects[oid]
            f.write("[%d]={%s,{%s}},\n" % (oid, q.lua_str(name), pts(sp)))
        f.write("} }\n")
    size = os.path.getsize(os.path.join(OUT, "Data.lua"))
    with_src = sum(1 for v in items.values() if v[3] or v[4] or v[5])
    print("trade goods %d (%d with a source), creatures/vendors %d, objects %d, Data.lua %d KB"
          % (len(items), with_src, sum(1 for v in npcs.values() if v), sum(1 for v in objects.values() if v), size // 1024))
    if "--deploy" in sys.argv:
        target = os.path.join(cfg["addonsDir"], "Outrider_Data_Reagents")
        if os.path.exists(target):
            shutil.rmtree(target)
        shutil.copytree(OUT, target)
        print("deployed to", target)


if __name__ == "__main__":
    main()
