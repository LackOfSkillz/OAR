-- tools/build_guide.lua: writes docs/USER_GUIDE.md from addon/Outrider/UI/HelpData.lua
-- (the in-game Help tab's text) plus every /ride command found in the code.
--   python tools/lua.py tools/build_guide.lua
-- Run after changing HelpData.lua or adding a command; the tests check the
-- guide is up to date.

local root = arg and arg[1] or "."
local function read(path)
  local f = assert(io.open(root .. "/" .. path, "rb"))
  local s = f:read("*a")
  f:close()
  return s
end

local ns = {}
local chunk = assert(loadstring(read("addon/Outrider/UI/HelpData.lua"), "HelpData"))
chunk("Outrider", ns)

-- commands: built-ins in Core/Slash.lua (add("name", "usage", ...)) and
-- ns.AddCommand("name", "usage", ...) anywhere in the addon
local cmds, seen = {}, {}
local function scan(text, pattern)
  for name, usage in text:gmatch(pattern) do
    if not seen[name] then seen[name] = true cmds[#cmds + 1] = { name, usage } end
  end
end
scan(read("addon/Outrider/Core/Slash.lua"), '\nadd%("([%w]+)", "([^"]*)"')
local files = {}
local toc = read("addon/Outrider/Outrider.toc")
for line in toc:gmatch("[^\r\n]+") do
  if line:match("%.lua$") and not line:match("^#") then files[#files + 1] = (line:gsub("\\", "/")) end
end
for _, f in ipairs(files) do
  local ok, text = pcall(read, "addon/Outrider/" .. f)
  if ok then scan(text, 'AddCommand%("([%w]+)", "([^"]*)"') end
end
table.sort(cmds, function(a, b) return a[1] < b[1] end)

local out = {}
local function w(s) out[#out + 1] = s end
w("# Outrider user guide")
w("")
w("What every part of Outrider does. The same text is in game: type `/ride` and open **Help**.")
w("This file is generated by `tools/build_guide.lua` from `addon/Outrider/UI/HelpData.lua`; edit that file, not this one.")
w("")
w("## Contents")
w("")
for _, sec in ipairs(ns.HelpData) do
  local anchor = sec[1]:lower():gsub("[^%w%s%-]", ""):gsub("%s", "-")
  w(string.format("- [%s](#%s)", sec[1], anchor))
end
w("- [All commands](#all-commands)")
w("")
for _, sec in ipairs(ns.HelpData) do
  w("## " .. sec[1])
  w("")
  if sec[2] then w(sec[2]) w("") end
  for _, t in ipairs(sec[3]) do w("- **" .. t[1] .. ".** " .. t[2]) end
  w("")
end
w("## All commands")
w("")
w("Type each after `/ride` (or `/outrider`). In game, the All commands page lists them with a Run button.")
w("")
w("| Command | What it does |")
w("|---|---|")
for _, c in ipairs(cmds) do w(string.format("| `/ride %s` | %s |", c[1], (c[2]:gsub("|", "\\|"):gsub("^%s+", "")))) end
w("")

local text = table.concat(out, "\n")
if arg and arg[2] == "--check" then
  local ok, cur = pcall(read, "docs/USER_GUIDE.md")
  if not ok or cur:gsub("\r\n", "\n") ~= text then
    print("docs/USER_GUIDE.md is out of date: run python tools/lua.py tools/build_guide.lua")
    os.exit(1)
  end
  print("user guide up to date (" .. #cmds .. " commands)")
  os.exit(0)
end
local f = assert(io.open(root .. "/docs/USER_GUIDE.md", "wb"))
f:write(text)
f:close()
print("wrote docs/USER_GUIDE.md: " .. #ns.HelpData .. " sections, " .. #cmds .. " commands")
