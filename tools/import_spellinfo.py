"""tools/import_spellinfo.py  (2026-11-19)

Builds addon/Outrider/Data/SpellInfo.lua from the class spellbook pages of
foreverchanges.pro ("every spell a class trains from 1 to 60", built from the
live Forever client). For each spell: the level a trainer teaches it (nil for
talents), whether it is a talent and of which tree, and the game's icon file.
Facts only (names, numbers, icon file names); verified = false until seen in
game. Gary OK'd the lookup (2026-11-19: "check these out").

Run: python -I tools/import_spellinfo.py <folder with <class>.html pages>
(save the pages first, e.g. curl https://foreverchanges.pro/spellbook/rogue)
"""
import html
import os
import re
import sys

TREES = {
    "HUNTER": {"beast": "bm", "marksmanship": "mm", "survival": "sv"},
    "PRIEST": {"discipline": "disc", "holy": "holy", "shadow": "shadow"},
    "MAGE": {"arcane": "arcane", "fire": "fire", "frost": "frost"},
    "WARRIOR": {"arms": "arms", "fury": "fury", "protection": "prot"},
    "ROGUE": {"assassination": "assassination", "combat": "combat", "subtlety": "subtlety"},
    "WARLOCK": {"affliction": "affliction", "demonology": "demonology", "destruction": "destruction"},
    "DRUID": {"balance": "balance", "feral": "feral", "restoration": "resto"},
    "PALADIN": {"holy": "holy", "protection": "prot", "retribution": "ret"},
    "SHAMAN": {"elemental": "elemental", "enhancement": "enhancement", "restoration": "resto"},
}


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(folder):
    out = ["-- Data/SpellInfo.lua  GENERATED by tools/import_spellinfo.py, do not edit by hand.",
           "-- Class spells on WoW Forever: trainer level (nil for a talent), talent tree, game icon.",
           "-- Source: foreverchanges.pro class spellbooks (built from the live client), read 2026-11-19.",
           "-- verified = false until seen in game. Used by the Macros page to place macros by level",
           "-- and build and to show a spell's icon before you know it.",
           "local _, ns = ...",
           "ns.SpellInfo = { verified = false, source = \"foreverchanges.pro spellbook, 2026-11-19\" }",
           "local S = ns.SpellInfo"]
    total = 0
    for cls in sorted(TREES):
        path = os.path.join(folder, cls.lower() + ".html")
        if not os.path.exists(path):
            continue
        t = open(path, encoding="utf-8", errors="replace").read()
        seen = {}
        for m in re.finditer(r'src="/icon/([^"]+?)\.jpg"/><span class="v2-row-text"><strong>(.*?)</strong>(.*?)</button>', t, re.S):
            icon, name, rest = m.group(1), html.unescape(m.group(2)).strip(), m.group(3)
            if name in seen:
                continue
            facts = re.search(r'sbk-row-facts">(.*?)</small>', rest, re.S)
            facts = html.unescape(re.sub(r"<[^>]+>", "", facts.group(1))) if facts else ""
            lv = re.search(r"from level (\d+)", facts)
            talent = "Talent" in facts or "talent point" in rest
            tab = re.split(r"\s*[�·]\s*", facts)[0].replace(" Talent", "").strip().lower()
            tree = TREES[cls].get(tab.split(" ")[0]) if talent else None
            seen[name] = (lv and int(lv.group(1)), tree, icon)
        out.append("S.%s = {" % cls)
        for name in sorted(seen):
            lv, tree, icon = seen[name]
            parts = ["level = %s" % (lv if lv else "nil"), "icon = %s" % q(icon)]
            if tree:
                parts.append("tree = %s" % q(tree))
            out.append("  [%s] = { %s }," % (q(name), ", ".join(parts)))
            total += 1
        out.append("}")
    open("addon/Outrider/Data/SpellInfo.lua", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("wrote addon/Outrider/Data/SpellInfo.lua: %d spells" % total)


if __name__ == "__main__":
    main(sys.argv[1])
