"""Build the load-on-demand word list addon Outrider_Data_Words from a SCOWL
(English Speller Database) list downloaded once from app.aspell.net
(Gary's OK, 2026-11-11: full size-60 list, US + GB spellings).

    py tools/build_words.py [path/to/scowl60.txt]

Writes addon/Outrider_Data_Words/{Outrider_Data_Words.toc, Words.lua,
LICENSE.txt}. The SCOWL licence allows redistribution with its copyright
notice, which goes into LICENSE.txt and the Lua header. Words are lowercased,
possessive "'s" forms dropped (the checker strips them), duplicates removed,
and stored as one newline-joined string per first two letters so the client
looks a word up with a plain string.find (small memory, no big table).
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "private", "scowl", "scowl60.txt")
OUT = os.path.join(ROOT, "addon", "Outrider_Data_Words")


def main():
    with open(SRC, encoding="utf-8") as f:
        text = f.read()
    header, sep, body = text.partition("\n---\n")
    if not sep:
        sys.exit("no '---' separator: not a SCOWL inline list")
    words = set()
    for line in body.splitlines():
        w = line.strip().lower()
        if not w or w.endswith("'s"):
            continue
        if any(c not in "abcdefghijklmnopqrstuvwxyz'-" for c in w):
            continue
        words.add(w)
    chunks = {}
    for w in sorted(words):
        chunks.setdefault(w[:2], []).append(w)
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "LICENSE.txt"), "w", encoding="utf-8", newline="\r\n") as f:
        f.write(header.strip() + "\n")
    with open(os.path.join(OUT, "Outrider_Data_Words.toc"), "w", encoding="utf-8", newline="\r\n") as f:
        f.write("## Interface: 16001\n## Title: Outrider Data: Words\n")
        f.write("## Notes: English word list for Outrider's chat spell check (SCOWL/ESDB, see LICENSE.txt).\n")
        f.write("## LoadOnDemand: 1\n\nWords.lua\n")
    with open(os.path.join(OUT, "Words.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("-- GENERATED by tools/build_words.py. English Speller Database (SCOWL) size 60,\n")
        f.write("-- US + GB spellings. Copyright 2000-2026 by Kevin Atkinson; see LICENSE.txt.\n")
        f.write("-- chunks[first two letters] = \"\\nword\\nword\\n...\\n\"\n")
        f.write("Outrider_DataWords = { source = \"SCOWL size 60 (US+GB)\", count = %d, chunks = {\n" % len(words))
        for key in sorted(chunks):
            joined = "\n" + "\n".join(chunks[key]) + "\n"
            # Lua drops the first newline after [=[, so add one to keep the leading "\n"
            f.write("[%s]=[=[\n%s]=],\n" % ('"' + key + '"', joined))
        f.write("} }\n")
    print("wrote %d words in %d chunks to %s" % (len(words), len(chunks), OUT))


if __name__ == "__main__":
    main()
